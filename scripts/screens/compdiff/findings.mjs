#!/usr/bin/env node
// node findings.mjs <rundir> [<findings.md>]
// Turns a run's systematic groups (fleet-summary rows, 3+ boards) into tracked findings and updates their status:
//   open      seen in this run
//   fixed     was open, absent from this run (a fix landed; confirm on the next build)
//   verified  absent in two consecutive runs
// State is kept in findings.json next to findings.md; findings.md is regenerated from it.
import fs from 'node:fs'
import path from 'node:path'

const run = process.argv[2]
const md = process.argv[3] || path.join(path.dirname(path.resolve(run)), '..', 'findings.md')
const stateFile = md.replace(/\.md$/, '.json')
const state = fs.existsSync(stateFile) ? JSON.parse(fs.readFileSync(stateFile, 'utf8')) : { runs: [], findings: {} }
const rows = fs.readFileSync(path.join(run, 'fleet-summary.md'), 'utf8').split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| component') && !l.startsWith('|---'))
const seen = new Set()
const chromeProp = /(^|\.)(buttons|tabCount|actions|controls)$|header \(title row\)/
for (const l of rows) {
	const [role, prop, dir, comps, boards, median, common, source] = l.split('|').slice(1, -1).map((s) => s.trim())
	const key = `${role} | ${prop} | ${dir}`
	seen.add(key)
	const f = state.findings[key] || { id: `F${String(Object.keys(state.findings).length + 1).padStart(3, '0')}`, first: run, status: 'open' }
	Object.assign(f, { role, prop, dir, comps: Number(comps), boards: Number(boards), median, common, owner: chromeProp.test(prop) ? 'dossiq (page/widget config)' : source, last: run })
	if (f.status !== 'open') { f.status = 'open'; f.reopened = run }
	state.findings[key] = f
}
for (const [key, f] of Object.entries(state.findings)) {
	if (seen.has(key)) continue
	if (f.status === 'open') { f.status = 'fixed'; f.fixedIn = run } else if (f.status === 'fixed' && f.fixedIn !== run) { f.status = 'verified'; f.verifiedIn = run }
}
if (!state.runs.includes(run)) state.runs.push(run)
fs.writeFileSync(stateFile, JSON.stringify(state, null, 1))
const list = Object.values(state.findings).sort((a, b) => (a.status > b.status ? 1 : a.status < b.status ? -1 : b.boards - a.boards))
const out = ['# COMPDIFF findings', '', `Generated by compdiff/findings.mjs. Runs: ${state.runs.join(', ')}. Status: open (seen in the last run), fixed (gone in the last run), verified (gone two runs running).`, '',
	'| id | status | component | property | direction | comps | boards | board -> live (most common) | owner | sent to | note |', '|---|---|---|---|---|---|---|---|---|---|---|']
for (const f of list) out.push(`| ${f.id} | ${f.status}${f.pending && f.status === 'open' ? ` (fix pending: ${f.pending})` : ''} | ${f.role} | ${f.prop} | ${f.dir} | ${f.comps} | ${f.boards} | ${f.common} | ${f.owner} | ${f.sentTo || ''} | ${f.note || ''} |`)
fs.writeFileSync(md, out.join('\n') + '\n')
console.log(`findings: ${list.filter((f) => f.status === 'open').length} open, ${list.filter((f) => f.status === 'fixed').length} fixed, ${list.filter((f) => f.status === 'verified').length} verified`)
